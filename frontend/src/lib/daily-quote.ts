// Sabit tohumlu karıştırma (mulberry32): her ortamda ve her yüklemede aynı sıra çıkar.
function shuffledIndices(length: number, seed: number): number[] {
  let state = seed >>> 0;
  const random = () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
  const order = Array.from({ length }, (_, index) => index);
  for (let index = length - 1; index > 0; index -= 1) {
    const swap = Math.floor(random() * (index + 1));
    [order[index], order[swap]] = [order[swap]!, order[index]!];
  }
  return order;
}

const QUOTE_ORDER = shuffledIndices(ALL_QUOTES.length, 20261014);

// Yerel takvim gününden gün numarası. Sayfadaki tarih satırıyla aynı kaynak kullanılır;
// aynı gün içinde herkes aynı sözü görür, gün değişince sıradaki söz gelir.
export function dailyQuote(date: Date = new Date()): DailyQuote {
  const dayNumber = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86_400_000);
  const position = ((dayNumber % ALL_QUOTES.length) + ALL_QUOTES.length) % ALL_QUOTES.length;
  return ALL_QUOTES[QUOTE_ORDER[position]!]!;
}
